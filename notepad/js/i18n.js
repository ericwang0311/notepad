    window.getLang = function () {
        try { return localStorage.getItem('app_lang') === 'en' ? 'en' : 'zh'; } catch (e) { return 'zh'; }
    };

    // 查表：中文原文 → 当前语言文案；未收录原样返回
    window.t = function (zh) {
        if (getLang() !== 'en') return zh;
        return Object.prototype.hasOwnProperty.call(EN, zh) ? EN[zh] : zh;
    };

    // 带占位符的查表：tf('类型：{type} · 文件：{name}', { type, name })
    window.tf = function (zh, vars) {
        let s = t(zh);
        if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
        return s;
    };

    // 应用静态文案：首次捕获原始中文（存 dataset），之后按语言回填
    window.applyI18n = function (root) {
        root = root || document;
        root.querySelectorAll('[data-i18n]').forEach(el => {
            if (!el.dataset.i18nZh) el.dataset.i18nZh = el.innerHTML;
            el.innerHTML = t(el.dataset.i18nZh);
        });
        root.querySelectorAll('[data-i18n-title]').forEach(el => {
            if (!el.dataset.i18nTitleZh) el.dataset.i18nTitleZh = el.getAttribute('title') || '';
            el.setAttribute('title', t(el.dataset.i18nTitleZh));
        });
        root.querySelectorAll('[data-i18n-ph]').forEach(el => {
            if (!el.dataset.i18nPhZh) el.dataset.i18nPhZh = el.getAttribute('placeholder') || '';
            el.setAttribute('placeholder', t(el.dataset.i18nPhZh));
        });
        document.documentElement.lang = getLang() === 'en' ? 'en' : 'zh-CN';
        // 首次捕获页面原始标题，之后按语言回填（兼容主页面与各内嵌页）
        if (!applyI18n._titleZh) applyI18n._titleZh = document.title;
        document.title = t(applyI18n._titleZh);
    };

    // 语言切换按钮文案：中文环境显示 EN（点击切英文），英文环境显示 中
    window.updateLangBtn = function () {
        const b = document.getElementById('langToggleBtn');
        if (b) b.textContent = getLang() === 'en' ? '中' : 'EN';
    };

    // 日历标题与星期行（按语言）
    window.calTitleText = function (year, month) {
        if (getLang() === 'en') {
            return ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][month] + ' ' + year;
        }
        return year + '年' + (month + 1) + '月';
    };
    window.calWeekdaysHtml = function () {
        const cells = getLang() === 'en'
            ? ['S', 'M', 'T', 'W', 'T', 'F', 'S']
            : ['日', '一', '二', '三', '四', '五', '六'];
        return '<div class="cal-weekdays">' + cells.map(c => '<span>' + c + '</span>').join('') + '</div>';
    };
